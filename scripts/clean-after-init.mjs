#!/usr/bin/env node
/**
 * clean-after-init.mjs
 *
 * Operator-triggered cleanup after the corpus init phase is complete.
 *
 * Removes every file marked `lifecycle: init-only` in its YAML frontmatter,
 * plus a small allowlist of root-level init-only files that cannot carry
 * frontmatter (e.g. KICKSTART.md). Containing skill folders are removed when
 * they become empty.
 *
 * Writes a manifest at `.corpus-pack/init-cleanup-manifest.yaml` recording
 * the pack version (from PACK_VERSION) and the exact list of paths that were
 * removed — so the cleanup remains auditable and the corpus retains a trace
 * of which version did the init.
 *
 * Usage:
 *   node scripts/clean-after-init.mjs            # dry-run, lists candidates
 *   node scripts/clean-after-init.mjs --write    # apply removals
 *
 * Rationale: keep the consumer repo focused on what makes the corpus *live*,
 * not on what bootstrapped it.
 */

import fs from 'node:fs';
import path from 'node:path';
import { normalizeText } from './lib/text.mjs';

const SCRIPT_DIR = path.dirname(new URL(import.meta.url).pathname);
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const SKILLS_ROOT = path.join(REPO_ROOT, '.github/skills');
const MANIFEST_DIR = path.join(REPO_ROOT, '.corpus-pack');
const MANIFEST_PATH = path.join(MANIFEST_DIR, 'init-cleanup-manifest.yaml');
const PACK_VERSION_PATH = path.join(REPO_ROOT, 'PACK_VERSION');

const WRITE = process.argv.includes('--write');

// Root-level init-only files that cannot carry frontmatter.
// Paths relative to REPO_ROOT.
const EXPLICIT_INIT_ONLY_PATHS = [
  'KICKSTART.md',
];

function* walkSkillDirs(root) {
  if (!fs.existsSync(root)) return;
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const full = path.join(root, entry.name);
    if (entry.isDirectory()) {
      const skillFile = path.join(full, 'SKILL.md');
      if (fs.existsSync(skillFile)) {
        yield { skillDir: full, skillFile };
      }
      yield* walkSkillDirs(full);
    }
  }
}

function parseFrontmatter(raw) {
  if (!raw.startsWith('---\n')) return null;
  const end = raw.indexOf('\n---', 4);
  if (end === -1) return null;
  const block = raw.slice(4, end);
  const out = {};
  for (const line of block.split('\n')) {
    const m = line.match(/^([a-zA-Z0-9_-]+):\s*(.*)$/);
    if (m) out[m[1]] = m[2].trim();
  }
  return out;
}

function readPackVersion() {
  if (!fs.existsSync(PACK_VERSION_PATH)) return 'unknown';
  const raw = fs.readFileSync(PACK_VERSION_PATH, 'utf8').trim();
  const firstLine = raw.split('\n')[0]?.trim() ?? 'unknown';
  return firstLine || 'unknown';
}

function collectSkillTargets() {
  const targets = [];
  for (const { skillDir, skillFile } of walkSkillDirs(SKILLS_ROOT)) {
    const raw = normalizeText(fs.readFileSync(skillFile, 'utf8'));
    const fm = parseFrontmatter(raw);
    if (!fm) continue;
    if (fm.lifecycle === 'init-only') {
      targets.push({
        type: 'skill-dir',
        path: skillDir,
        relPath: path.relative(REPO_ROOT, skillDir),
        name: fm.name ?? path.basename(skillDir),
      });
    }
  }
  return targets;
}

function collectExplicitTargets() {
  const targets = [];
  for (const rel of EXPLICIT_INIT_ONLY_PATHS) {
    const full = path.join(REPO_ROOT, rel);
    if (fs.existsSync(full)) {
      targets.push({
        type: 'explicit-file',
        path: full,
        relPath: rel,
        name: path.basename(rel),
      });
    }
  }
  return targets;
}

function removePath(p) {
  if (!fs.existsSync(p)) return;
  fs.rmSync(p, { recursive: true, force: true });
}

function pruneEmptyParents(startDir, stopAt) {
  let cur = path.dirname(startDir);
  while (cur.startsWith(stopAt) && cur !== stopAt) {
    if (!fs.existsSync(cur)) break;
    const entries = fs.readdirSync(cur);
    if (entries.length === 0) {
      fs.rmdirSync(cur);
      cur = path.dirname(cur);
    } else {
      break;
    }
  }
}

function yamlList(items) {
  if (items.length === 0) return '[]';
  return '\n' + items.map(it => `  - ${it}`).join('\n');
}

function writeManifest({ packVersion, removed }) {
  if (!fs.existsSync(MANIFEST_DIR)) {
    fs.mkdirSync(MANIFEST_DIR, { recursive: true });
  }
  const now = new Date().toISOString();
  const lines = [
    '# corpus-pack init cleanup manifest',
    '# Records the post-init cleanup pass performed on this repo.',
    '# Generated by scripts/clean-after-init.mjs — do not edit by hand.',
    '',
    `pack_version: "${packVersion}"`,
    `cleaned_at: "${now}"`,
    `removed_count: ${removed.length}`,
    `removed_paths:${yamlList(removed.map(r => `"${r}"`))}`,
    '',
  ];
  fs.writeFileSync(MANIFEST_PATH, lines.join('\n'));
}

function main() {
  const skillTargets = collectSkillTargets();
  const explicitTargets = collectExplicitTargets();
  const all = [...skillTargets, ...explicitTargets];

  console.log(`Pack root: ${REPO_ROOT}`);
  console.log(`Pack version: ${readPackVersion()}`);
  console.log('');
  console.log(`Init-only skills (frontmatter): ${skillTargets.length}`);
  for (const t of skillTargets) {
    console.log(`  - ${t.relPath}   (skill: ${t.name})`);
  }
  console.log('');
  console.log(`Explicit init-only files: ${explicitTargets.length}`);
  for (const t of explicitTargets) {
    console.log(`  - ${t.relPath}`);
  }
  console.log('');

  if (all.length === 0) {
    console.log('Nothing to clean. Either init was already cleaned, or no file is marked init-only.');
    return;
  }

  if (!WRITE) {
    console.log(`Total candidates: ${all.length}`);
    console.log('Re-run with --write to apply removals + emit manifest.');
    return;
  }

  const removed = [];
  for (const t of all) {
    removePath(t.path);
    if (t.type === 'skill-dir') {
      pruneEmptyParents(t.path, SKILLS_ROOT);
    }
    removed.push(t.relPath);
  }

  writeManifest({
    packVersion: readPackVersion(),
    removed,
  });

  console.log(`Removed: ${removed.length} path(s).`);
  console.log(`Manifest: ${path.relative(REPO_ROOT, MANIFEST_PATH)}`);
  console.log('');
  console.log('Init cleanup complete. The repo now contains only the runtime');
  console.log('layer needed to keep the corpus alive. Re-init paths require');
  console.log('the upstream pack — by design.');
}

main();
